-- Monobank acquiring for ZNAIDENO Premium (149 UAH / 30 days).
CREATE TABLE IF NOT EXISTS public.monobank_payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id text NOT NULL UNIQUE,
  reference text NOT NULL UNIQUE,
  telegram_id bigint NOT NULL,
  amount_minor integer NOT NULL CHECK (amount_minor > 0),
  currency_code integer NOT NULL DEFAULT 980,
  status text NOT NULL DEFAULT 'created'
    CHECK (status IN ('created','processing','success','failure','expired','reversed')),
  page_url text,
  paid_at timestamptz,
  premium_until timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS monobank_payments_telegram_id_created_idx
  ON public.monobank_payments (telegram_id, created_at DESC);
ALTER TABLE public.monobank_payments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.monobank_payments FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.monobank_payments TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.monobank_payments_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.activate_monobank_premium(
  p_invoice_id text,
  p_amount_minor integer,
  p_currency_code integer
) RETURNS TABLE(activated boolean, telegram_id bigint, premium_until timestamptz)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  payment_row public.monobank_payments%ROWTYPE;
  current_expiry timestamptz;
  new_expiry timestamptz;
BEGIN
  SELECT * INTO payment_row
  FROM public.monobank_payments
  WHERE invoice_id = p_invoice_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Unknown Monobank invoice';
  END IF;

  IF payment_row.amount_minor <> p_amount_minor
     OR payment_row.currency_code <> p_currency_code
     OR p_amount_minor <> 14900
     OR p_currency_code <> 980 THEN
    RAISE EXCEPTION 'Monobank payment amount/currency mismatch';
  END IF;

  IF payment_row.status = 'success' AND payment_row.premium_until IS NOT NULL THEN
    RETURN QUERY SELECT false, payment_row.telegram_id, payment_row.premium_until;
    RETURN;
  END IF;

  SELECT u.premium_until INTO current_expiry
  FROM public.users u
  WHERE u.telegram_id = payment_row.telegram_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'User record not found for Monobank invoice';
  END IF;

  new_expiry := GREATEST(COALESCE(current_expiry, now()), now()) + interval '30 days';

  UPDATE public.users
  SET tariff = 'premium', premium_until = new_expiry
  WHERE telegram_id = payment_row.telegram_id;

  UPDATE public.monobank_payments
  SET status = 'success', paid_at = COALESCE(paid_at, now()),
      premium_until = new_expiry, updated_at = now()
  WHERE invoice_id = p_invoice_id;

  RETURN QUERY SELECT true, payment_row.telegram_id, new_expiry;
END;
$$;
REVOKE ALL ON FUNCTION public.activate_monobank_premium(text, integer, integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.activate_monobank_premium(text, integer, integer) TO service_role;
