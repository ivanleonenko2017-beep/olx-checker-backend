-- External Monobank Jar donations: sponsor badge only, not Premium access.
ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS is_sponsor boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS sponsor_since timestamptz;

CREATE TABLE IF NOT EXISTS public.mono_jar_sync_state (
  id smallint PRIMARY KEY CHECK (id = 1),
  last_time bigint NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO public.mono_jar_sync_state (id, last_time)
VALUES (1, GREATEST(EXTRACT(EPOCH FROM now())::bigint - 120, 0))
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.sponsor_donations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mono_transaction_id text NOT NULL UNIQUE,
  telegram_id bigint NOT NULL,
  jar_id text NOT NULL,
  amount_minor bigint NOT NULL CHECK (amount_minor > 0),
  currency_code integer,
  comment text,
  occurred_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS sponsor_donations_telegram_id_idx
  ON public.sponsor_donations (telegram_id);
CREATE INDEX IF NOT EXISTS sponsor_donations_occurred_at_idx
  ON public.sponsor_donations (occurred_at DESC);

ALTER TABLE public.mono_jar_sync_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sponsor_donations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.mono_jar_sync_state FROM anon, authenticated;
REVOKE ALL ON public.sponsor_donations FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.mono_jar_sync_state TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.sponsor_donations TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.sponsor_donations_id_seq TO service_role;
