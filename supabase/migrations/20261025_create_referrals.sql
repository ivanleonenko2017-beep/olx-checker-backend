-- Run this once in Supabase SQL Editor to enable referral counting and rewards.
-- Safe to run repeatedly.
create table if not exists public.referrals (
  id bigint generated by default as identity primary key,
  inviter_telegram_id bigint not null,
  invitee_telegram_id bigint not null,
  created_at timestamptz not null default now(),
  constraint referrals_invitee_unique unique (invitee_telegram_id),
  constraint referrals_no_self_referral check (inviter_telegram_id <> invitee_telegram_id)
);

create index if not exists referrals_inviter_idx
  on public.referrals (inviter_telegram_id);

alter table public.referrals enable row level security;

-- The backend uses the Supabase service-role key; no public client access is needed.
