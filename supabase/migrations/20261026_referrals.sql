-- Referral attribution for OLX Checker.
-- One Telegram account can be attributed to only one inviter.
create table if not exists public.referrals (
  id bigint generated by default as identity primary key,
  inviter_telegram_id bigint not null,
  invitee_telegram_id bigint not null unique,
  created_at timestamptz not null default now(),
  constraint referrals_no_self_referral check (inviter_telegram_id <> invitee_telegram_id)
);

create index if not exists referrals_inviter_telegram_id_idx
  on public.referrals (inviter_telegram_id);

