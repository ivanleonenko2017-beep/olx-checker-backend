-- Ledger for confirmed Telegram Stars purchases. Keep charge IDs unique to prevent duplicate fulfillment.
create table if not exists public.star_payments (
  id bigint generated by default as identity primary key,
  telegram_payment_charge_id text not null unique,
  provider_payment_charge_id text,
  telegram_id bigint not null,
  currency text not null check (currency = 'XTR'),
  total_amount integer not null check (total_amount > 0),
  invoice_payload text not null,
  created_at timestamptz not null default now()
);

create index if not exists star_payments_telegram_id_idx
  on public.star_payments (telegram_id);

alter table public.star_payments enable row level security;
