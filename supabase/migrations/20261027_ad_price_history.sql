-- Persistent per-filter price snapshots for price-drop alerts.
-- Apply in Supabase SQL Editor before deploying the matching worker code.
create table if not exists public.ad_price_history (
  id bigint generated by default as identity primary key,
  filter_id text not null,
  ad_link text not null,
  last_price numeric not null check (last_price > 0),
  updated_at timestamptz not null default now(),
  unique (filter_id, ad_link)
);

create index if not exists ad_price_history_filter_updated_idx
  on public.ad_price_history (filter_id, updated_at desc);

comment on table public.ad_price_history is
  'Latest observed listing price per ZNAIDENO filter, used for deduplicated price-drop alerts.';
