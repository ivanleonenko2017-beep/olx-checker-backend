-- Run this migration in the Supabase SQL Editor before enabling referral tracking.
-- The backend uses the service-role key server-side; do not expose that key to the client.
create table if not exists public.referrals (
  id bigint generated by default as identity primary key,
  inviter_telegram_id bigint not null,
  invitee_telegram_id bigint not null,
  created_at timestamptz not null default now(),
  constraint referrals_no_self_referral check (inviter_telegram_id <> invitee_telegram_id),
  constraint referrals_one_inviter_per_invitee unique (invitee_telegram_id)
);

create index if not exists referrals_inviter_telegram_id_idx
  on public.referrals (inviter_telegram_id);

alter table public.referrals enable row level security;
